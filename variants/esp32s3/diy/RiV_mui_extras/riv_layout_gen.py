"""Generates the live portrait/landscape relayout for the main screen of meshtastic-device-ui.

The portrait (ui_240x320) and the landscape (ui_320x240) generated layouts create the same objects with the same styles; only the
geometry differs. The portrait create function registers every object it creates, and this module turns the geometry lines of both
files into riv_apply_layout(land), which sets them on the registered objects at run time.
"""
import re

WHITELIST = [
    re.compile(r"^lv_obj_(set_pos|set_size|set_width|set_height|set_x|set_y|set_align|set_flex_flow|set_flex_align|set_flex_grow|set_scrollbar_mode)\(obj, "),
    re.compile(r"^lv_obj_set_style_(align|x|y|width|height|min_width|max_width|min_height|max_height|pad_\w+|margin_\w+|flex_flow|flex_main_place|flex_cross_place|flex_track_place|flex_grow|text_line_space)\(obj, "),
    re.compile(r"^lv_label_set_long_mode\(obj, "),
]
FLAG = re.compile(r"^lv_obj_(add|remove)_flag\(obj, ([A-Z_| ]+)\);")
CREATE = re.compile(r"^lv_obj_t \*obj = (lv_\w+)_create\(")
NAME = re.compile(r"^objects\.(\w+) = obj;")


def _body(src):
    a = src.index("void create_screen_main_screen() {")
    b = src.index("void tick_screen_main_screen()")
    return a, b


def _keep(t):
    if "parent_obj" in t or "objects." in t or "&" in t:
        return False
    if any(w.match(t) for w in WHITELIST):
        return True
    m = FLAG.match(t)
    if m:
        flags = m.group(2)
        return "HIDDEN" not in flags and "CLICKABLE" not in flags and "DISABLED" not in flags
    return False


def parse(lines):
    objs = []
    cur = None
    last_named = None
    off = 0
    for ln in lines:
        t = ln.strip()
        m = CREATE.match(t)
        if m:
            cur = {"type": m.group(1), "props": [], "name": None, "anchor": last_named, "off": off}
            objs.append(cur)
            off += 1
            continue
        if cur is None:
            continue
        m = NAME.match(t)
        if m:
            cur["name"] = m.group(1)
            last_named = m.group(1)
            off = 0
            cur["anchor"] = m.group(1)
            cur["off"] = 0
            continue
        if t.startswith("lv_") and "(obj," in t and _keep(t):
            cur["props"].append(t)
    return objs


def _key(o):
    return (o["anchor"], o["off"])


def generate(src_p, src_l):
    """returns (riv_layout.c text, patched portrait screens.c text, stats)"""
    src_p = re.sub(r"^[ \t]*riv_reg\(obj\);\n", "", src_p, flags=re.M).replace("extern void riv_reg(lv_obj_t *o);\n", "")
    a, b = _body(src_p)
    la, lb = _body(src_l)
    P = parse(src_p[a:b].split("\n"))
    L = parse(src_l[la:lb].split("\n"))
    lmap = {}
    for i, o in enumerate(L):
        k = _key(o)
        if k in lmap:
            lmap[k] = None  # ambiguous
        else:
            lmap[k] = i
    out = []
    matched = skipped = 0
    for i, p in enumerate(P):
        j = lmap.get(_key(p))
        if j is None or L[j]["type"] != p["type"]:
            skipped += 1
            continue
        matched += 1
        pp, ll = p["props"], L[j]["props"]
        if pp == ll:
            continue
        out.append("    obj = riv_objs[%d];\n    if (land) {\n%s    } else {\n%s    }\n" % (
            i, "".join("        %s\n" % x for x in ll), "".join("        %s\n" % x for x in pp)))
    n = len(P)
    c = ('#include <string.h>\n\n#include "screens.h"\n#include "images.h"\n#include "fonts.h"\n#include "styles.h"\n#include "ui.h"\n\n'
         "// generated by riv_layout_gen.py: live portrait / landscape layout of the main screen\n"
         "lv_obj_t *riv_objs[%d];\nstatic int riv_n = 0;\nstatic int riv_wanted = %d;\n\n"
         "void riv_reg(lv_obj_t *o)\n{\n    if (riv_n < riv_wanted)\n        riv_objs[riv_n++] = o;\n}\n\n"
         "int riv_registered(void)\n{\n    return riv_n;\n}\n\n"
         "void riv_apply_layout(int land)\n{\n    lv_obj_t *obj;\n    if (riv_n < riv_wanted)\n        return;\n%s}\n" % (n + 8, n, "".join(out)))
    # the portrait create function registers what it creates
    body = src_p[a:b]
    lines = body.split("\n")
    res = []
    for ln in lines:
        res.append(ln)
        if CREATE.match(ln.strip()):
            indent = ln[: len(ln) - len(ln.lstrip())]
            res.append(indent + "riv_reg(obj);")
    patched = src_p[:a] + "\n".join(res) + src_p[b:]
    if "extern void riv_reg(lv_obj_t *o);" not in patched:
        patched = patched.replace("objects_t objects;\n", "objects_t objects;\nextern void riv_reg(lv_obj_t *o);\n", 1)
    return c, patched, {"objects": n, "matched": matched, "skipped": skipped, "changed": len(out)}
