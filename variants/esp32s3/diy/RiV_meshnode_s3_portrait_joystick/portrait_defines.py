Import("env")

# LANDSCAPE DEFINES INHERITED FROM THE BASE ENV: DROP THEM SO ONLY ONE VIEW IS BUILT
DROP = {"-DVIEW_320x240", "-DLGFX_ROTATION=3", "-DDISPLAY_SIZE=320x240", "-DTFT_WIDTH=320", "-DTFT_HEIGHT=240"}

# LIBRARIES RE-READ BUILD_FLAGS, SO FILTER THE FLAG LIST
flags = env.get("BUILD_FLAGS", [])
env.Replace(BUILD_FLAGS=[f for f in flags if f.replace(" ", "") not in DROP])
