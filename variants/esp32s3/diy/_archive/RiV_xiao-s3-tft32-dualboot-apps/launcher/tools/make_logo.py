# Converts the launcher logos to 64 colour indexed images (8 bit index plus an RGB565 palette) for the launcher buttons.
# Run:  python -I tools/make_logo.py        (needs Pillow)
import os
from PIL import Image, ImageChops

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "assets")
SRC_DIR = os.path.join(HERE, "..", "src")
NL = chr(10)
COLORS = 64
MESHTASTIC_W = 132  # inside the button
PATHFINDER_BOX = 124  # square the Pathfinder logo is fitted into


def write_header(name, im):
    q = im.quantize(colors=COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:COLORS * 3]
    pal += [0] * (COLORS * 3 - len(pal))
    w, h = q.size
    idx = list(q.getdata())
    path = os.path.join(SRC_DIR, "logo_%s.h" % name)
    up = name.upper()
    with open(path, "w", newline=NL) as f:
        f.write("// generated by tools/make_logo.py, do not edit" + NL + "#pragma once" + NL + "#include <stdint.h>" + NL)
        f.write("#define LOGO_%s_W %d" % (up, w) + NL + "#define LOGO_%s_H %d" % (up, h) + NL)
        f.write("static const uint16_t logo_%s_pal[%d] = {" % (name, COLORS) + NL)
        for i in range(COLORS):
            r, g, b = pal[i * 3:i * 3 + 3]
            f.write("  0x%04X," % (((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)) + NL)
        f.write("};" + NL)
        f.write("static const uint8_t logo_%s[LOGO_%s_W * LOGO_%s_H] = {" % (name, up, up) + NL)
        for i in range(0, len(idx), 24):
            f.write("  " + ",".join(str(v) for v in idx[i:i + 24]) + "," + NL)
        f.write("};" + NL)
    print("wrote", path, w, "x", h, len(idx) + COLORS * 2, "bytes")


im = Image.open(os.path.join(ASSETS, "meshtastic_ui.png")).convert("RGB")
h = round(im.size[1] * MESHTASTIC_W / im.size[0])
write_header("meshtastic", im.resize((MESHTASTIC_W, h), Image.LANCZOS))

im = Image.open(os.path.join(ASSETS, "pathfinder_logo.jpg")).convert("RGB")
box = ImageChops.difference(im, Image.new("RGB", im.size, (255, 255, 255))).convert("L").point(lambda v: 255 if v > 24 else 0).getbbox()
im = im.crop(box)
scale = min(PATHFINDER_BOX / im.size[0], PATHFINDER_BOX / im.size[1])
write_header("pathfinder", im.resize((max(1, round(im.size[0] * scale)), max(1, round(im.size[1] * scale))), Image.LANCZOS))
