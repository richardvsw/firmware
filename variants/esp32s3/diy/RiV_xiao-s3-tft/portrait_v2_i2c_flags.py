Import("env")

# I2C AND SENSORS WERE EXCLUDED IN THE BASE ENV, PORTRAIT V2 ROTATIONS REPLACE THE EXPERIMENT
DROP = {
    "-DMESHTASTIC_EXCLUDE_I2C=1",
    "-DMESHTASTIC_EXCLUDE_ENVIRONMENTAL_SENSOR=1",
    "-DLGFX_ROTATION=0",
    "-DLGFX_TOUCH_ROTATION=2",
}

flags = env.get("BUILD_FLAGS", [])
env.Replace(BUILD_FLAGS=[f for f in flags if f.replace(" ", "") not in DROP])
