Import("env")

# I2C AND SENSORS WERE EXCLUDED IN THE BASE ENV, LCD RST MOVES TO EN, TOUCH MAPPING IS SET HERE, THE OTHER ENVS KEEP THEIR OWN
DROP = {
    "-DMESHTASTIC_EXCLUDE_I2C=1",
    "-DMESHTASTIC_EXCLUDE_ENVIRONMENTAL_SENSOR=1",
    "-DLGFX_PIN_RST=3",
    "-DTFT_RST=3",
    "-DLGFX_TOUCH_X_MIN=300",
    "-DLGFX_TOUCH_X_MAX=3900",
    "-DLGFX_TOUCH_Y_MIN=300",
    "-DLGFX_TOUCH_Y_MAX=3900",
}

flags = env.get("BUILD_FLAGS", [])
env.Replace(
    BUILD_FLAGS=[
        f for f in flags if f.replace(" ", "") not in DROP and not f.replace(" ", "").startswith("-DLGFX_TOUCH_ROTATION=")
    ]
)

# TOUCH: ROTATION 7 WITH RANGES SHIFTED TO MATCH THE PANEL, NO STORED CALIBRATION
env.Append(
    BUILD_FLAGS=[
        "-DLGFX_TOUCH_ROTATION=7",
        "-DLGFX_TOUCH_X_MIN=410",
        "-DLGFX_TOUCH_X_MAX=4010",
        "-DLGFX_TOUCH_Y_MIN=0",
        "-DLGFX_TOUCH_Y_MAX=3600",
    ]
)
